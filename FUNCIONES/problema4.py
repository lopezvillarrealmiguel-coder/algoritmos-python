'''
Crea una función llamada obtener_doble(n) que tome un número
y devuelva su valor multiplicado por 2.

Prueba 1: obtener_doble(14): 28
Prueba 2: obtener_doble(0): 0
Prueba 3: obtener_doble(-5): -10
'''

